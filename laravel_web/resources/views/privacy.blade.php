                        <span>Article IV — Disclosure and Sharing of Personal Data</span>
                    </h2>
                    <div class="space-y-3 text-xs sm:text-sm">
                        <p><strong>4.1 Service Participant Sharing:</strong> Data is shared between service participants exclusively as required for active trip, rental, or delivery fulfillment (e.g. driver name, vehicle plate, live GPS, recipient phone number).</p>
                        <p><strong>4.2 Corporate Service Processors:</strong> We disclose data to vetted corporate service providers including Stripe, PayPal, Google Maps, Checkr, AWS, and Mailgun under strict non-disclosure and processing agreements.</p>
                        <p><strong>4.3 No Data Sales:</strong> Ride My Cars does NOT sell or rent personal information to third-party data brokers or marketing aggregators.</p>
