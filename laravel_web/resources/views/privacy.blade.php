                        <span>Article II — Categories of Personal Data Collected</span>
                    </h2>
                    <div class="space-y-4 text-xs sm:text-sm">
                        <p>We collect personal information directly from users, automatically during service interaction, and from verified third-party screening services:</p>
                        <div class="space-y-2">
                            <p><strong>2.1 User Identity & Account Data:</strong> Legal full name, email address, telephone number, profile photograph, photographic identification, government ID numbers, driver/operator license numbers, background screening clearances (Checkr), vehicle registration, fleet insurance policies, and rental inspection logs.</p>
                            <p><strong>2.2 Logistics Consignment Data:</strong> Sender name/phone, recipient name/phone, parcel description, declared value, pickup/drop-off addresses, delivery instructions, and 4-digit recipient PIN code verification.</p>
                            <p><strong>2.3 Real-Time Geolocation Data:</strong> Precise GPS location coordinates (latitude/longitude) collected while the application is active during ride hailing, chauffeur service, or package delivery fulfillment.</p>
                            <p><strong>2.4 Technical & Device Data:</strong> Device model, IP address, operating system, network connection type, crash logs, and essential authentication cookies.</p>
                            <p><strong>2.5 Financial Transaction Data (§2.1.4):</strong> Payment transaction reference IDs, payment method types (Stripe, PayPal, Apple Pay, Paystack, Mobile Money), gross fares, and masked card/wallet suffixes (e.g. <code>**** 4242</code>). <em>Raw credit/debit card numbers and CVV security codes are NEVER stored in our database.</em></p>
                        </div>
                    </div>
