                        <p><strong>3.3 Financial Settlement Architecture (§3.1.3):</strong> Personal data is processed to execute secure payment collection from Customers and distribute disbursements to Service Providers through PCI-DSS Level 1 certified payment networks (Stripe, PayPal, Paystack, MoMo).</p>
