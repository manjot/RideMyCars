                        <span>Article V — Data Security and Retention Frameworks</span>
                    </h2>
                    <div class="space-y-3 text-xs sm:text-sm">
                        <p><strong>5.1 Technical Security Measures:</strong> Data in transit is protected using TLS 1.3 encryption. Passwords are cryptographically salted and hashed using Bcrypt. Databases utilize role-based access control (RBAC) and restricted firewall segments.</p>
                        <p><strong>5.2 Statutory Retention Framework (§5.2):</strong> Personal account profiles are deactivated upon approved account erasure requests. Booking transaction logs, payment histories, and tax records are retained for <strong>7 years</strong> following account deactivation to comply with statutory accounting, tax, and anti-money laundering (AML) laws.</p>
                    </div>
